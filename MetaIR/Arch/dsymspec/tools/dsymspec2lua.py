#!/usr/bin/env python3
"""Convert .dsymspec.yaml files to Lua data modules.

Each output file is `return { ... }` with the same content as the JSON document
from dsymspec2json.py: encoder bodies appear as the Algol-like `source` string
that domsymas consumes. The backend extension is not a Lua table (it is large
and machine-generated); it is stored as JSON text in `backend_json`, which the
consumer decodes. This is the same arrangement the old backend/*.lua modules used.

Usage:
    python3 tools/dsymspec2lua.py                          # all specs -> build/lua/<arch>.lua
    python3 tools/dsymspec2lua.py -o out/ x86.dsymspec.yaml
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import dsymspec_core as core  # noqa: E402

LUA_KEYWORDS = {
    "and", "break", "do", "else", "elseif", "end", "false", "for", "function", "goto",
    "if", "in", "local", "nil", "not", "or", "repeat", "return", "then", "true",
    "until", "while",
}
_IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def lua_string(s: str) -> str:
    out = ['"']
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif o < 0x20 or o == 0x7F:
            out.append("\\%03d" % o)
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def lua_key(k: str) -> str:
    if _IDENT.match(k) and k not in LUA_KEYWORDS:
        return k
    return "[%s]" % lua_string(k)


def lua_value(v, depth: int) -> str:
    pad = "  " * (depth + 1)
    close = "  " * depth
    if v is None:
        return "nil"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, str):
        return lua_string(v)
    if isinstance(v, list):
        if not v:
            return "{}"
        if all(not isinstance(x, (list, dict)) for x in v):
            return "{ " + ", ".join(lua_value(x, depth + 1) for x in v) + " }"
        items = [pad + lua_value(x, depth + 1) + "," for x in v]
        return "{\n" + "\n".join(items) + "\n" + close + "}"
    if isinstance(v, dict):
        if not v:
            return "{}"
        pairs = [(k, x) for k, x in v.items() if x is not None]
        if all(not isinstance(x, (list, dict)) for _, x in pairs):
            return "{ " + ", ".join("%s = %s" % (lua_key(k), lua_value(x, depth + 1))
                                    for k, x in pairs) + " }"
        items = [pad + lua_key(k) + " = " + lua_value(x, depth + 1) + ","
                 for k, x in pairs]
        return "{\n" + "\n".join(items) + "\n" + close + "}"
    raise TypeError("cannot represent %r in Lua" % (type(v),))


def long_string(text: str) -> str:
    """Lua long bracket with enough '=' to avoid clashing with the text."""
    level = 0
    while ("]" + "=" * level + "]") in text:
        level += 1
    eq = "=" * level
    return "[%s[%s]%s]" % (eq, text, eq)


def render(spec_name: str, doc: dict, backend_text: str | None) -> str:
    head = [
        "-- Generated by tools/dsymspec2lua.py from %s. Do not edit." % spec_name,
        "-- Data only. Same content as dsymspec2json.py output; `backend_json` is",
        "-- the backend extension as JSON text (decode it with a JSON parser).",
        "return {",
    ]
    body = []
    for key, value in doc.items():
        if key == "backend":
            continue
        body.append("  %s = %s," % (lua_key(key), lua_value(value, 1)))
    if backend_text is not None:
        body.append("  backend_json = %s," % long_string(backend_text))
    return "\n".join(head + body + ["}", ""])


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("files", nargs="*", type=Path, help="spec files (default: all in repo root)")
    ap.add_argument("-o", "--out-dir", type=Path, default=core.REPO_ROOT / "build" / "lua",
                    help="directory for <arch>.lua files (default: build/lua)")
    ap.add_argument("--no-backend", action="store_true", help="omit backend_json")
    args = ap.parse_args(argv)

    files = args.files or core.discover_specs()
    if not files:
        print("no .dsymspec.yaml files found", file=sys.stderr)
        return 2

    status = 0
    for path in files:
        try:
            spec = core.require_valid(path)
            doc = core.build_document(spec, path.parent, with_backend=False)
        except core.SpecError as exc:
            print(exc, file=sys.stderr)
            status = 1
            continue
        backend_text = None
        if spec.get("backend") and not args.no_backend:
            backend_text = (path.parent / spec["backend"]["file"]).read_text(encoding="utf-8")
        arch = core.arch_of(spec)
        args.out_dir.mkdir(parents=True, exist_ok=True)
        target = args.out_dir / (arch + ".lua")
        with open(target, "w", encoding="utf-8", newline="\n") as f:
            f.write(render(path.name, doc, backend_text))
        print("wrote %s" % target)
    return status


if __name__ == "__main__":
    sys.exit(main())
