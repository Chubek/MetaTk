#!/usr/bin/env python3
"""Generate the bounded MLVM RV64 encoder from the YAML architecture bank.

Only audited, single-word, relocation-free encoders are executable here. This
is not an interpreter for arbitrary DomSymAsCC bodies. Instruction expressions,
register numbers, argument/result ABI registers and immediate bounds come from
Arch, never from a second opcode table in MLVM.
"""
import argparse
import json
import re
from pathlib import Path

from dsymspec_core import parse_body, require_valid


ROOT = Path(__file__).resolve().parents[3]
DEFAULT_SPEC = Path(__file__).resolve().parents[1] / "riscv64.dsymspec.yaml"
DEFAULT_OUTPUT = ROOT / "MLVM/generated/arch/riscv64.qs"
# Supported mechanisms, not instruction encodings.
OPERATIONS = ("add", "sub", "mul", "and", "or", "xor", "slt", "addi", "ret")


def generate(path):
    spec = require_valid(path)
    target = spec["targets"][0]
    if target["arch"] != "riscv64" or target["addr_size"] != 64 or target["byte_order"] != "little":
        raise ValueError("MLVM encoder requires little-endian RV64")
    if not {"i", "m"}.issubset(target["features"]):
        raise ValueError("MLVM leaf encoder requires RV64IM features")
    policy = json.loads((path.parent / spec["backend"]["file"]).read_text())["compiler_policy"]["allocation"]
    regs = {r["name"].lower(): r["enc"] for r in spec["registers"] if r["class"] == "gpr" and r["width"] == 64}
    canonical = [r for name, r in regs.items() if re.fullmatch(r"x\d+", name)]
    if sorted(canonical) != list(range(len(canonical))):
        raise ValueError("non-contiguous RV64 register bank")
    arguments = [regs[name.lower()] for name in policy["argument_registers"]]
    reserved = {regs[name.lower()] for name in policy["reserved"] + policy["callee_saved"]}
    ra = regs[policy["return_address_register"].lower()]
    if len(set(arguments)) != len(arguments) or set(arguments) & (reserved | {ra}):
        raise ValueError("unsafe MLVM leaf register allocation")
    result = regs[policy["return_registers"][0].lower()]
    encoders = {e["name"]: e for e in spec["encoders"]}
    forms = spec["forms"]
    lines = ["// Generated by Arch/dsymspec/tools/generate_mlvm.py; do not edit.",
             f"const REGISTER_COUNT = {len(canonical)};",
             f"const ZERO = {regs['zero']};", f"const RESULT = {result};",
             "fn allocation(): list<int> { return " + json.dumps(arguments) + "; }",
             "fn encode(name: str, rd, rs1, rs2, imm) {",
             "    if (rd < 0 || rd >= REGISTER_COUNT || rs1 < 0 || rs1 >= REGISTER_COUNT ||",
             "        rs2 < 0 || rs2 >= REGISTER_COUNT) die(\"MLVM RV64: invalid register\");"]
    for name in OPERATIONS:
        e = encoders[name]
        body = parse_body(e["body"], name)
        if e["max_bytes"] != 4 or len(body) != 1 or body[0].op != "EMIT32LE":
            raise ValueError(f"unsupported MLVM encoder mechanism: {name}")
        expr = body[0].args[0]
        identifiers = set(re.findall(r"\b[A-Za-z_]\w*\b", re.sub(r"0[xX][0-9a-fA-F]+", "0", expr)))
        if identifiers - {"rd", "rs1", "rs2", "imm"}:
            raise ValueError(f"unbound MLVM encoder operand: {name}")
        lines.append(f'    if (name == "{name}") {{')
        if "imm" in identifiers:
            matches = [f for f in forms if f["encoder"] == name]
            if len(matches) != 1:
                raise ValueError(f"ambiguous MLVM form: {name}")
            immediates = [o for o in matches[0]["operands"] if o["kind"] == "imm"]
            if len(immediates) != 1:
                raise ValueError(f"missing MLVM immediate bounds: {name}")
            lo, hi = immediates[0]["imm_min"], immediates[0]["imm_max"]
            lines.append(f'        if (imm < {lo} || imm > {hi}) die("MLVM RV64: immediate out of range");')
        lines.extend([f"        return {expr};", "    }"])
    lines.extend(['    die("MLVM RV64: unsupported encoder");', "    return 0;", "}", ""])
    return "\n".join(lines)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check", action="store_true")
    p.add_argument("--spec", type=Path, default=DEFAULT_SPEC)
    p.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = p.parse_args()
    text = generate(args.spec.resolve())
    if args.check:
        if not args.output.is_file() or args.output.read_text() != text:
            p.exit(1, f"stale MLVM encoder: {args.output}\n")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text)


if __name__ == "__main__":
    main()
