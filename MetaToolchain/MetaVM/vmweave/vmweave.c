#include "vmweave.h"
#include <ctype.h>
#include <string.h>
static mvm_status fail(mvm_error *e, mvm_status s, const char *msg) {
    mvm_error_clear(e);
    if (e) { e->status=s; snprintf(e->message,sizeof e->message,"%s",msg); }
    return s;
}
mvm_status vmwv_compile_assembly(const char *s,size_t n,mvm_module **out,mvm_error *e) {
    return mvm_compile(s,n,0,out,e);
}
mvm_status vmwv_emit_c(const mvm_module *m,const char *name,FILE *f,mvm_error *e) {
    mvm_buffer b = {0}; mvm_status s; size_t i;
    static const char *keywords[]={"auto","break","case","char","const","continue","default","do",
        "double","else","enum","extern","float","for","goto","if","inline","int","long","register",
        "restrict","return","short","signed","sizeof","static","struct","switch","typedef","union",
        "unsigned","void","volatile","while","main"};
    if (!name || !f || !name[0] || !((name[0]>='A' && name[0]<='Z') || (name[0]>='a' && name[0]<='z')))
        return fail(e,MVM_INVALID,"invalid or reserved C factory name");
    if(strlen(name)>255 || !strncmp(name,"mvm_",4) || !strncmp(name,"MVM_",4) || !strncmp(name,"vmwv_",5))
        return fail(e,MVM_INVALID,"reserved or excessive C factory name");
    for(i=1;name[i];++i) if(!((name[i]>='A'&&name[i]<='Z') || (name[i]>='a'&&name[i]<='z') ||
        (name[i]>='0'&&name[i]<='9') || name[i]=='_')) return fail(e,MVM_INVALID,"invalid C factory name");
    for(i=0;i<sizeof keywords/sizeof keywords[0];++i)if(!strcmp(name,keywords[i]))
        return fail(e,MVM_INVALID,"C keyword cannot be a factory name");
    if(ferror(f))return fail(e,MVM_IO,"output stream already failed");
    s=mvm_serialize(m,&b,e); if(s!=MVM_OK) { mvm_buffer_dispose(&b); return s; }
    /* The generated factory deserializes with default Machinery limits. Reject
     * oversized modules before emitting a factory that cannot load itself. */
    if(b.size>mvm_default_limits().max_module_bytes) {
        mvm_buffer_dispose(&b);return fail(e,MVM_LIMIT,"module exceeds generated factory load limit");
    }
    fprintf(f,"/* Generated by VMWeave. Link with MetaVM Machinery. */\n#include \"MetaVM.h\"\n");
    fprintf(f,"mvm_status %s(mvm_module **out,mvm_error *error) {\nstatic const unsigned char data[] = {",name);
    for(i=0;i<b.size;++i) {
        if(i%12==0) fputc('\n',f);
        fprintf(f,"%s%u",i?",":"",(unsigned)b.data[i]);
    }
    fputs("};\nreturn mvm_deserialize(data,sizeof data,0,out,error);\n}\n",f);
    mvm_buffer_dispose(&b);
    if(ferror(f)) return fail(e,MVM_IO,"cannot write generated C");
    return MVM_OK;
}

mvm_status vmwv_emit_c_file(const mvm_module *m,const char *name,const char *path,mvm_error *e) {
    FILE *staging;
    mvm_buffer buffer={0};
    unsigned char block[4096];
    size_t count;
    mvm_status status;
    if(!path||!*path)return fail(e,MVM_INVALID,"invalid output path");
    staging=tmpfile();
    if(!staging)return fail(e,MVM_IO,"cannot create C staging stream");
    status=vmwv_emit_c(m,name,staging,e);
    if(status==MVM_OK && (fflush(staging)!=0 || fseek(staging,0,SEEK_SET)!=0))
        status=fail(e,MVM_IO,"cannot rewind C staging stream");
    while(status==MVM_OK && (count=fread(block,1,sizeof block,staging))!=0) {
        if(count>128u*1024u*1024u-buffer.size)status=fail(e,MVM_LIMIT,"generated C exceeds 128 MiB");
        else {
            status=mvm_buffer_append(&buffer,block,count);
            if(status!=MVM_OK)status=fail(e,status,"cannot buffer generated C");
        }
    }
    if(ferror(staging) && status==MVM_OK)status=fail(e,MVM_IO,"cannot read C staging stream");
    if(fclose(staging)!=0 && status==MVM_OK)status=fail(e,MVM_IO,"cannot close C staging stream");
    if(status==MVM_OK)status=mvm_write_file_atomic(path,buffer.data,buffer.size,e);
    mvm_buffer_dispose(&buffer);return status;
}
