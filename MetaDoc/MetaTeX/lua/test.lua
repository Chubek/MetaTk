local open = assert(package.loadlib(assert(arg[1]), "luaopen_lmtex"))
local m = open()
local engine = m.new()
local html, diagnostics = engine:compile([[Hello \textbf{Lua}.]])
assert(html:find("<p>Hello <strong>Lua</strong>.</p>", 1, true), html)
assert(diagnostics == "")
local json = assert(engine:compile([[Hello \textbf{Lua}.]], "json"))
assert(json:find('"bold"', 1, true))
local pdf = assert(engine:compile("Hello Lua.", "pdf"))
assert(pdf:sub(1, 8) == "%PDF-1.4")
assert(pdf:find("(Hello Lua.) Tj", 1, true))
assert(engine:fragment([[\def\word{persistent}]], "text"))
assert(engine:fragment([[\word]], "text") == "persistent\n\n")
local bad, error = engine:compile([[\undefined]])
assert(bad == nil and error:find("undefined", 1, true))
bad, error = engine:compile("test", "missing-device")
assert(bad == nil and error:find("unsupported device", 1, true))
engine:close()
assert(not pcall(function() engine:compile("closed") end))
engine:close()
print("Lua binding tests passed")
